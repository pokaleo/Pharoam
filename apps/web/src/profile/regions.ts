/** A country to choose, with its name in the person's language. */
export interface RegionOption {
  /** Its ISO 3166-1 alpha-2 code, such as `GB`. */
  readonly code: string;
  /** Its name, such as "United Kingdom". */
  readonly name: string;
}

/**
 * Names every country in a language, sorted by name.
 *
 * @param locale - The language to name and sort them in, such as `en-GB`.
 * @returns Every country, as code and name, sorted by name.
 */
export function regionOptions(locale: string): readonly RegionOption[] {
  const names = new Intl.DisplayNames([locale], { type: "region" });
  const collator = new Intl.Collator(locale);
  return REGION_CODES.map((code) => ({ code, name: names.of(code) ?? code })).sort((a, b) =>
    collator.compare(a.name, b.name),
  );
}
